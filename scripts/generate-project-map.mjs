import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";

const root = path.resolve(import.meta.dirname, "..");
const maxDepth = 4;
const localOnlyPrefixes = ["Chat_GPT_Context/"];

function isLocalOnly(relativePath) {
  return localOnlyPrefixes.some(
    (prefix) => relativePath === prefix.slice(0, -1) || relativePath.startsWith(prefix),
  );
}

function listRepositoryFiles() {
  const output = execFileSync(
    "git",
    ["ls-files", "--cached", "--others", "--exclude-standard", "-z"],
    { cwd: root, encoding: "utf8" },
  );

  return output
    .split("\0")
    .filter(Boolean)
    .filter((relativePath) => !isLocalOnly(relativePath))
    .filter((relativePath) => fs.existsSync(path.join(root, relativePath)));
}

const repositoryFiles = listRepositoryFiles();
const files = repositoryFiles.filter(
  (relativePath) => relativePath.split("/").length - 1 <= maxDepth,
);
const dirs = new Set();

for (const relativePath of repositoryFiles) {
  const parts = relativePath.split("/");

  for (let length = 1; length < parts.length && length <= maxDepth + 1; length += 1) {
    dirs.add(parts.slice(0, length).join("/"));
  }
}

const output = [
  "# Learn Malay Project Map",
  "",
  `Generated: ${new Date().toISOString().slice(0, 10)}`,
  "",
  "This file is generated by `scripts/generate-project-map.mjs` from tracked and non-ignored working-tree files.",
  "Local prompt-context files are intentionally excluded.",
  "",
  "## Directories",
  "",
  "```text",
  ...[...dirs].sort(),
  "```",
  "",
  "## Files",
  "",
  "```text",
  ...files.sort(),
  "```",
  "",
].join("\n");

fs.writeFileSync(path.join(root, "PROJECT_MAP.md"), output);
console.log("Generated PROJECT_MAP.md");
